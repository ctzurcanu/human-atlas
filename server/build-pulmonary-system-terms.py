"""Build the complete pulmonary inventory for the independent Systems browser."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
hierarchy = json.loads((ROOT / 'public/assets/ta98.json').read_text())
parents = json.loads((ROOT / 'app/data/ta98-parents.json').read_text())['parents']
terms = []
for node in hierarchy['nodes']:
    code = node['id']
    if not (code.startswith('A06.5.') or code == 'A07.1.01.001'
            or code.startswith('A07.1.02.') and 1 <= int(code.rsplit('.', 1)[1]) <= 19):
        continue
    parent = parents.get(code)
    # Systems is an organ browser, not a copy of the source TA98 partonomy.
    # The source extract places both left lobes below "base of lung".
    if code in {'A06.5.02.015', 'A06.5.02.020'}:
        parent = 'A06.5.01.003'
    if code in {'A07.1.01.001', 'A07.1.02.001', 'A07.1.02.018', 'A07.1.02.019'}:
        parent = 'A06.5.01.001'
    terms.append({'id': code, 'name': node['name'], 'parent': parent})
assert len(terms) == 70 and len({term['id'] for term in terms}) == 70
(ROOT / 'app/pulmonary-system-inventory.ts').write_text('// Generated by server/build-pulmonary-system-terms.py. Systems navigation only.\nexport default ' + json.dumps({
    'source': hierarchy['source'],
    'view': 'systems',
    'terms': terms,
}, ensure_ascii=False, indent=2) + ';\n')
print('Systems pulmonary inventory: 70 terms')
