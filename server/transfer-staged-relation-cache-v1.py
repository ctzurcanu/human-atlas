"""Transfer complete future-revision exports after exact source equivalence.

Only module path aliases are normalized. Future parent bytes must have been
generated by the unchanged hierarchy builder against both actual catalogues.
"""
from pathlib import Path
import hashlib,json,sys

ROOT=Path(__file__).resolve().parents[1]
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def main(base):
    base=Path(base).resolve();future=base/'future-relations-workspace-v1'
    assert base.is_relative_to(ROOT) and future.is_dir()
    live=json.loads((base/'live-resolver-inputs-v1.json').read_bytes())
    exporter='scripts/export-structural-relation-edges.mjs'
    live[exporter]=sha(ROOT/exporter)
    physical={str((ROOT/k).resolve()):k for k in live}
    assert sha(ROOT/'scripts/build-ta98-hierarchy.py')==sha(future/'scripts/build-ta98-hierarchy.py')
    parent='app/data/ta98-parents.json';proof=[]
    for sex in ['male','female']:
        catalogue=future/f'.local-models/ta98-review/bowel-wall-local-atlas/{sex}/atlas.json'
        current=base/'proposed-atlas.json' if sex=='male' else ROOT/f'.local-models/ta98-review/bowel-wall-local-atlas/{sex}/atlas.json'
        assert sha(catalogue)==sha(current)
        source=sha(catalogue);path=future/f'.local-models/geometry-workbench/dependency-relations/{source}/{sex}.json'
        data=json.loads(path.read_bytes());canonical={};aliases=[]
        for key,value in data['resolverInputs'].items():
            assert sha(future/key)==value
            target=key if key in live else physical[str((future/key).resolve())]
            if target!=parent:assert value==live[target]
            canonical[target]=value
            if target!=key:aliases.append(dict(exportPath=key,canonicalPath=target,physicalPath=str((future/key).resolve()),sha256=value))
        assert set(canonical)==set(live)
        assert canonical[parent]==sha(future/parent)
        data['resolverInputs']=canonical;data['verifiedResolverPathAliases']=aliases
        data['futureParentSnapshotBinding']=dict(path=str(future/parent),sha256=sha(future/parent),maleCatalogueSha256=sha(base/'proposed-atlas.json'),hierarchyBuilderSha256=sha(ROOT/'scripts/build-ta98-hierarchy.py'))
        target=ROOT/f'.local-models/geometry-workbench/dependency-relations/{source}/{sex}.json'
        target.parent.mkdir(parents=True,exist_ok=True);target.write_text(json.dumps(data,separators=(',',':')))
        proof.append(dict(sex=sex,path=str(target),sha256=sha(target),completeBatches=data['stagedProducer']['completeOrdinalBatches'],edges=len(data['edges']),aliasCount=len(aliases),exactCanonicalInputSet=len(canonical)))
    (base/'relation-cache-transfer-proof.json').write_text(json.dumps(proof,indent=2)+'\n')
    print(json.dumps(proof))

if __name__=='__main__':main(sys.argv[1])
