const parts=file=>JSON.parse(readFileSync(file,'utf8')).parts;
const related=(list,name)=>{
 const source=list.find(part=>part.name===name);
 assert.ok(source,`${name} must exist in this atlas`);
 return anatomicalRelations(source,list);
};
const has=(relations,kind,name)=>relations.some(relation=>relation.kind===kind&&relation.target.name===name);
const link=(relations,kind,name)=>relations.find(relation=>relation.kind===kind&&relation.target.name===name);

